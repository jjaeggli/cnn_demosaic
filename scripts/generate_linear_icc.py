# Generates minimal linear-TRC ICC v2.4 matrix profiles for the linear output
# encodings that the Compact-ICC-Profiles collection does not provide
# (linear sRGB, linear Rec.2020, linear ProPhoto/ROMM).
#
# The profiles follow the conventions of the bundled Compact-ICC-Profiles
# (CC0, https://github.com/saucecontrol/Compact-ICC-Profiles):
#
# - Only the required tags are present: desc, wtpt, cprt, rXYZ/gXYZ/bXYZ and
#   rTRC/gTRC/bTRC.
# - The colorant XYZ values are Bradford-adapted to the ICC PCS illuminant
#   (D50), while the wtpt tag records the native white point of the color
#   space (D65 for sRGB and Rec.2020, D50 for ProPhoto).
# - The TRC is a 'curv' tag with a count of 0, which the ICC v2 spec defines
#   as the identity (linear) function.
#
# Run from the repository root:
#
#   python scripts/generate_linear_icc.py

import struct
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = REPO_ROOT / "src" / "cnn_demosaic" / "profiles"

# ICC v2.4 profile version and the D50 PCS illuminant.
ICC_VERSION = 0x02400000
D50_XYZ = np.array([0.9642, 1.0, 0.8249])

COPYRIGHT = "Generated by cnn_demosaic. GNU GPL v3 or later."

# xy chromaticities from the published color space specifications.
SPACES = {
    "sRGB-linear-v2.icc": {
        "description": "sRGB linear",
        "primaries": [(0.6400, 0.3300), (0.3000, 0.6000), (0.1500, 0.0600)],
        "white": (0.3127, 0.3290),
    },
    "Rec2020-linear-v2.icc": {
        "description": "Rec2020 linear",
        "primaries": [(0.708, 0.292), (0.170, 0.797), (0.131, 0.046)],
        "white": (0.3127, 0.3290),
    },
    "ProPhoto-linear-v2.icc": {
        "description": "ProPhoto linear",
        # ProPhoto (ROMM RGB) is natively referenced to D50.
        "primaries": [(0.7347, 0.2653), (0.1596, 0.8404), (0.0366, 0.0001)],
        "white": (0.3457, 0.3585),
    },
}

# Bradford chromatic adaptation matrix.
BRADFORD = np.array(
    [
        [0.8951, 0.2664, -0.1614],
        [-0.7502, 1.7135, 0.0367],
        [0.0389, -0.0685, 1.0296],
    ]
)


def s15_fixed16(value: float) -> bytes:
    return struct.pack(">i", round(float(value) * 65536))


def xy_to_xyz(x: float, y: float) -> np.ndarray:
    return np.array([x / y, 1.0, (1.0 - x - y) / y])


def rgb_to_xyz_matrix(primaries, white_xy):
    """Builds the RGB -> XYZ matrix with white luminance Y = 1.0."""
    r, g, b = primaries
    m = np.array(
        [
            [r[0], g[0], b[0]],
            [r[1], g[1], b[1]],
            [1.0 - r[0] - r[1], 1.0 - g[0] - g[1], 1.0 - b[0] - b[1]],
        ]
    )
    white_xyz = xy_to_xyz(*white_xy)
    scale = np.linalg.solve(m, white_xyz)
    return m @ np.diag(scale), white_xyz


def bradford_adapt(matrix, src_white_xyz):
    """Adapts the matrix columns from the source white to the D50 PCS."""
    src_cone = BRADFORD @ src_white_xyz
    dst_cone = BRADFORD @ D50_XYZ
    adaptation = np.linalg.inv(BRADFORD) @ np.diag(dst_cone / src_cone) @ BRADFORD
    return adaptation @ matrix


def desc_tag(text: str) -> bytes:
    # textDescriptionType per ICC v2.
    ascii_text = text.encode("ascii") + b"\x00"
    return (
        b"desc"
        + b"\x00" * 4
        + struct.pack(">I", len(ascii_text))
        + ascii_text
        + struct.pack(">I", 0)  # Unicode language code
        + struct.pack(">I", 0)  # Unicode count
        + struct.pack(">H", 0)  # ScriptCode code
        + struct.pack(">B", 0)  # ScriptCode count
        + b"\x00" * 67  # ScriptCode data
    )


def text_tag(text: str) -> bytes:
    return b"text" + b"\x00" * 4 + text.encode("ascii") + b"\x00"


def xyz_tag(values) -> bytes:
    return b"XYZ " + b"\x00" * 4 + b"".join(s15_fixed16(v) for v in values)


def curv_linear_tag() -> bytes:
    # curv with a count of 0 is the identity (linear) function per ICC v2.
    return b"curv" + b"\x00" * 4 + struct.pack(">I", 0)


def build_profile(description: str, rgb_to_xyz_d50, wtpt_xyz) -> bytes:
    timestamp = datetime.now(UTC).replace(microsecond=0)

    tags = [
        (b"desc", desc_tag(description)),
        (b"wtpt", xyz_tag(wtpt_xyz)),
        (b"cprt", text_tag(COPYRIGHT)),
        (b"rXYZ", xyz_tag(rgb_to_xyz_d50[:, 0])),
        (b"gXYZ", xyz_tag(rgb_to_xyz_d50[:, 1])),
        (b"bXYZ", xyz_tag(rgb_to_xyz_d50[:, 2])),
        (b"rTRC", curv_linear_tag()),
        (b"gTRC", curv_linear_tag()),
        (b"bTRC", curv_linear_tag()),
    ]

    tag_table_size = 4 + 12 * len(tags)
    offset = 128 + tag_table_size
    table_entries, tag_data = b"", b""
    for signature, data in tags:
        table_entries += signature + struct.pack(">II", offset, len(data))
        padding = -len(data) % 4
        tag_data += data + b"\x00" * padding
        offset += len(data) + padding

    total_size = 128 + len(table_entries) + 4 + len(tag_data)

    header = bytearray(128)
    header[0:4] = struct.pack(">I", total_size)
    header[8:12] = struct.pack(">I", ICC_VERSION)
    header[12:16] = b"mntr"
    header[16:20] = b"RGB "
    header[20:24] = b"XYZ "
    header[24:36] = struct.pack(
        ">6H",
        timestamp.year,
        timestamp.month,
        timestamp.day,
        timestamp.hour,
        timestamp.minute,
        timestamp.second,
    )
    header[36:40] = b"acsp"
    header[64:68] = struct.pack(">I", 0)  # Perceptual rendering intent.
    header[68:80] = xyz_tag(D50_XYZ)[8:20]  # PCS illuminant.

    return bytes(header) + struct.pack(">I", len(tags)) + table_entries + tag_data


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for filename, space in SPACES.items():
        rgb_to_xyz, white_xyz = rgb_to_xyz_matrix(space["primaries"], space["white"])
        rgb_to_xyz_d50 = bradford_adapt(rgb_to_xyz, white_xyz)
        profile = build_profile(space["description"], rgb_to_xyz_d50, white_xyz)
        output_path = OUTPUT_DIR / filename
        output_path.write_bytes(profile)
        print(f"wrote {output_path.relative_to(REPO_ROOT)} ({len(profile)} bytes)")


if __name__ == "__main__":
    main()
