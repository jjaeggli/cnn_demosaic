# Module for locating the ICC color profiles embedded in output image files.

import functools
from importlib import resources

from cnn_demosaic.color_convert import (
    OUTPUT_COLORSPACE_PROPHOTO,
    OUTPUT_COLORSPACE_REC2020,
    OUTPUT_COLORSPACE_SRGB,
)

PROFILES_MODULE = "cnn_demosaic.profiles"

# Display-referred profiles from the CC0 Compact-ICC-Profiles collection
# (https://github.com/saucecontrol/Compact-ICC-Profiles).
SRGB_V2_MAGIC = "sRGB-v2-magic.icc"
REC2020_V2_MAGIC = "Rec2020-v2-magic.icc"
PROPHOTO_V2_MAGIC = "ProPhoto-v2-magic.icc"

# Linear scene-referred profiles generated by scripts/generate_linear_icc.py.
SRGB_LINEAR_V2 = "sRGB-linear-v2.icc"
REC2020_LINEAR_V2 = "Rec2020-linear-v2.icc"
PROPHOTO_LINEAR_V2 = "ProPhoto-linear-v2.icc"

# Maps (output_linear, output_colorspace) to the ICC profile resource name.
# The primaries and the transfer function of the profile must both match the
# encoded output data.
ICC_PROFILES = {
    (False, OUTPUT_COLORSPACE_SRGB): SRGB_V2_MAGIC,
    (True, OUTPUT_COLORSPACE_SRGB): SRGB_LINEAR_V2,
    (False, OUTPUT_COLORSPACE_REC2020): REC2020_V2_MAGIC,
    (True, OUTPUT_COLORSPACE_REC2020): REC2020_LINEAR_V2,
    (False, OUTPUT_COLORSPACE_PROPHOTO): PROPHOTO_V2_MAGIC,
    (True, OUTPUT_COLORSPACE_PROPHOTO): PROPHOTO_LINEAR_V2,
}


@functools.cache
def get_icc_profile(output_linear: bool, output_colorspace: str) -> bytes | None:
    """Returns the ICC profile bytes matching the output encoding.

    Args:
        output_linear: Whether the output values are linear (scene-referred)
            rather than encoded with the color space transfer function.
        output_colorspace: The output color space name, one of
            VALID_OUTPUT_COLORSPACES.

    Returns:
        The raw ICC profile bytes, or None when no profile matches the
        requested combination.
    """
    filename = ICC_PROFILES.get((bool(output_linear), output_colorspace))
    if filename is None:
        return None
    return resources.files(PROFILES_MODULE).joinpath(filename).read_bytes()
